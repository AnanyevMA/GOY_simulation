// ── Вспомогательная математика ──
export function clamp(v, min, max) {
    return Math.max(min, Math.min(max, v));
}

/**
 * Возвращает количество порванных рукавов в конкретной секции (0..numSections-1).
 * Позволяет честно локализовать даже 1–3 порванных рукава по секциям.
 */
export function getTornBagsInSection(secIdx, totalTorn, numSections = config.numSections) {
    if (totalTorn <= 0) return 0;
    return Math.floor((totalTorn + numSections - 1 - secIdx) / numSections);
}


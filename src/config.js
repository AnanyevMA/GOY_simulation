// ── Вспомогательная математика ──
export function clamp(v, min, max) {
    return Math.max(min, Math.min(max, v));
}

/** Модельное время одного тика, ч (1 тик = 6 с модельного времени при simTimeFactor = 60) */
export const SIM_DT_H = (config.tickRealSec * config.simTimeFactor) / 3600;

/**
 * Точка росы водяного пара (°C) по формуле Магнуса для смеси при 101.325 кПа.
 * @param {number} humidityPct — объёмная доля H₂O в газе, %
 * @param {number} acidShift   — поправка на кислые компоненты (HF/SO₂), °C
 */
export function dewPointC(humidityPct, acidShift = config.acidDewShift) {
    const x = Math.max(0.5, humidityPct);                // нижняя граница 0.5%: защита от ln(0) и нефизичных T_росы < −20°C
    const pv = (x / 100) * 101.325;                      // парциальное давление пара, кПа
    const g = Math.log(pv / 0.61094);                    // 0.61094 кПа ≈ 6.1094 гПа (константа Магнуса)
    return (243.12 * g) / (17.62 - g) + acidShift;
}

/** Множитель активности сорбции от температуры (1.0 при T ≤ tempKStart) */
export function sorptionTempFactor(T) {
    return T > config.tempKStart ? Math.exp(-config.tempKRate * (T - config.tempKStart)) : 1.0;
}

/** Доля газа, захваченная укрытием, при разрежении draftPa (Па, знак не важен) */
export function captureEfficiency(draftPa) {
    const d = Math.abs(draftPa) / config.captureDraft0;
    return config.captureMax * (1 - Math.exp(-Math.pow(d, config.captureExp)));
}

/**
 * Возвращает количество порванных рукавов в конкретной секции (0..numSections-1).
 * Позволяет честно локализовать даже 1–3 порванных рукава по секциям.
 */
export function getTornBagsInSection(secIdx, totalTorn, numSections = config.numSections) {
    if (totalTorn <= 0) return 0;
    return Math.floor((totalTorn + numSections - 1 - secIdx) / numSections);
}

